    <article>
        <h3 class="title"># WAS BENÖTIGEN WIR FÜR EINEN AUFTRITT?</h3>
        <p>Wir versuchen, unseren Aufbau simpel und effizient zu halten, damit wir möglichst jede Veranstaltungsgröße bedienen können. Da wir als junge Band jedoch auch clever sparen müssen, bringen wir in erster Linie den Bühnenaufbau selbst mit und sind neben der Bühne auf den Veranstalter angewiesen. Wir benötigen:</p>
        <p class="text">- <b>Bühne:</b> fester, ebener Untergrund, Mindestgröße ca. 6 × 4 m, idealerweise: 8 × 6 m<br>- <b>Strom:</b> 6 normale 230V Steckdosen<br>- <b>Stagebox:</b> 16 Kanäle von der Bühne zur FOH<br>- <b>FOH-Mischpult:</b> mind. 16 Kanäle (jew. EQ & Comp, Hall für Vocals)<br>- <b>PA-Anlage:</b> der Veranstaltungsgröße entsprechend<br>- <b>FOH-Techniker</b></p>
        <p>Die genaue Positioniserung von Strom und Musikern lässt sich im Technical Rider einsehen.</p>
    </article>
    <article>
        <h3 class="title"># MONITORING - SILENT STAGE</h3>
        <p class="text">Wir verwenden <b>In-Ear-Monitoring</b>. Das erlaubt uns, eine sogenannte <b>„Silent Stage“</b> zu erzeugen – auf der Bühne zu hören sind nur Schlagzeug und Gesang, alles andere läuft direkt über DI in unser Rack. Das minimiert Feedback-Gefahr und bietet mehr Kontrolle über den Mix. Für Veranstalter heißt das:</p>
        <p class="text">✔ schnellerer Aufbau<br>✔ weniger Rückkopplungsstress<br>✔ voller Fokus auf den FOH-Mix</p>
    </article>
    <article>
        <h3 class="title"># UNSER TECHNISCHES SETUP</h3>
